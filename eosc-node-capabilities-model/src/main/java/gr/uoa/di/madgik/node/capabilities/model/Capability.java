package gr.uoa.di.madgik.node.capabilities.model;

import tools.jackson.databind.PropertyNamingStrategies;
import tools.jackson.databind.annotation.JsonNaming;

import java.net.URI;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Locale;
import java.util.Objects;
import java.util.Optional;
import java.util.UUID;

/**
 * Describes a single capability exposed by a node endpoint.
 *
 * <p>A capability includes the capability type, the concrete service endpoint, an optional
 * version, an optional API specification location, and metadata about the communication
 * protocol and operational status.</p>
 *
 * <p>The {@code protocol} and {@code status} fields are intentionally stored as {@link String}
 * values to preserve extensibility. Known values are documented by {@link Protocol} and
 * {@link Status}, but values outside those enums are still accepted and normalized when set.</p>
 *
 * <p>The {@code id} is a UUID. When a capability has no id, {@link #deriveId(String, URI)} provides a
 * deterministic name-based (version 5) UUID from its capability type and endpoint. An existing id is never
 * replaced, so ids generated by other means remain valid.</p>
 */
@JsonNaming(PropertyNamingStrategies.SnakeCaseStrategy.class)
public class Capability {

    private static final UUID ID_NAMESPACE = UUID.fromString("766855ab-a9f4-4bfe-b807-c4a37acdd6f3");

    private UUID id;
    private String capabilityType;
    private URI endpoint;
    private String version;
    private URI apiSpec;
    private String protocol = Protocol.REST.value();
    private String status = Status.OPERATIONAL.value();

    public Capability() {
    }

    /**
     * Derives a deterministic version 5 UUID from a capability type and endpoint.
     *
     * <p>The capability type is trimmed and lower-cased, and the endpoint is normalized with its scheme
     * and host lower-cased, so cosmetic differences yield the same id.</p>
     *
     * @return the derived id, or {@code null} if the type is null or blank or the endpoint is null
     */
    public static UUID deriveId(String capabilityType, URI endpoint) {
        if (capabilityType == null || capabilityType.isBlank() || endpoint == null) {
            return null;
        }
        String name = capabilityType.trim().toLowerCase(Locale.ROOT) + "\n" + canonicalEndpoint(endpoint);
        return nameBasedSha1Uuid(ID_NAMESPACE, name);
    }

    private static String canonicalEndpoint(URI endpoint) {
        URI normalized = endpoint.normalize();
        String value = normalized.toString();
        String scheme = normalized.getScheme();
        if (scheme == null) {
            return value;
        }

        String rest = value.substring(scheme.length());
        String authority = normalized.getRawAuthority();
        String host = normalized.getHost();
        if (authority != null && host != null && rest.startsWith("://" + authority)) {
            String canonicalAuthority = authority.replace(host, host.toLowerCase(Locale.ROOT));
            rest = "://" + canonicalAuthority + rest.substring(3 + authority.length());
        }
        return scheme.toLowerCase(Locale.ROOT) + rest;
    }

    private static UUID nameBasedSha1Uuid(UUID namespace, String name) {
        MessageDigest sha1;
        try {
            sha1 = MessageDigest.getInstance("SHA-1");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-1 is not available", e);
        }

        sha1.update(ByteBuffer.allocate(16)
                .putLong(namespace.getMostSignificantBits())
                .putLong(namespace.getLeastSignificantBits())
                .array());
        byte[] hash = sha1.digest(name.getBytes(StandardCharsets.UTF_8));

        hash[6] = (byte) ((hash[6] & 0x0f) | 0x50);
        hash[8] = (byte) ((hash[8] & 0x3f) | 0x80);
        ByteBuffer bytes = ByteBuffer.wrap(hash, 0, 16);
        return new UUID(bytes.getLong(), bytes.getLong());
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getCapabilityType() {
        return capabilityType;
    }

    public void setCapabilityType(String capabilityType) {
        this.capabilityType = capabilityType;
    }

    public URI getEndpoint() {
        return endpoint;
    }

    public void setEndpoint(URI endpoint) {
        this.endpoint = endpoint;
    }

    public void setEndpoint(String endpoint) {
        this.endpoint = endpoint == null ? null : URI.create(endpoint);
    }

    public String getVersion() {
        return version;
    }

    public void setVersion(String version) {
        this.version = version;
    }

    public URI getApiSpec() {
        return apiSpec;
    }

    public void setApiSpec(URI apiSpec) {
        this.apiSpec = apiSpec;
    }

    public String getProtocol() {
        return protocol;
    }

    public void setProtocol(String protocol) {
        if (protocol == null) {
            this.protocol = null;
            return;
        }

        Optional<Protocol> p = Protocol.fromValue(protocol);
        if (p.isPresent()) {
            this.protocol = p.get().value();
        } else {
            this.protocol = protocol.trim().toUpperCase(Locale.ROOT);
        }
    }

    public void setProtocol(Protocol protocol) {
        this.protocol = Objects.requireNonNull(protocol, "protocol").value();
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        if (status == null) {
            this.status = null;
            return;
        }

        Optional<Status> s = Status.fromValue(status);
        if (s.isPresent()) {
            this.status = s.get().value();
        } else {
            this.status = status.trim().toUpperCase(Locale.ROOT);
        }
    }

    public void setStatus(Status status) {
        this.status = Objects.requireNonNull(status, "status").value();
    }

}
